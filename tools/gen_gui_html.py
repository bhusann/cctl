#!/usr/bin/env python3
"""Embed the GUI web assets into a C string header for cctl_gui_server.inc.

Usage: gen_gui_html.py <index.html> <icon.svg> <out.inc>
Mirrors tools/gen_skill_inc.py: keep the embedded copy in sync with the
checked-in web files.
"""
import sys


def to_c_string(data: bytes) -> str:
    text = data.decode("utf-8")
    chunks: list[str] = []
    buf: list[str] = []
    size = 0
    for ch in text:
        if ch == "\\":
            s = "\\\\"
        elif ch == '"':
            s = '\\"'
        elif ch == "\n":
            s = "\\n"
        elif ch == "\r":
            s = "\\r"
        elif ch == "\t":
            s = "\\t"
        elif ord(ch) < 32:
            s = "\\%03o" % ord(ch)
        else:
            s = ch
        buf.append(s)
        size += len(s)
        if size > 200:
            chunks.append('"' + "".join(buf) + '"')
            buf, size = [], 0
    if buf:
        chunks.append('"' + "".join(buf) + '"')
    return "\n".join(chunks)


def main() -> int:
    html_path, icon_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(html_path, "rb") as f:
        html = f.read()
    with open(icon_path, "rb") as f:
        icon = f.read()
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_gui_html.py — do not edit by hand.\n"
                "   Sources: gui/web/index.html, docs/cctl-icon.svg */\n\n")
        f.write("static const char GUI_HTML[] =\n" + to_c_string(html) + ";\n\n")
        f.write("static const char GUI_ICON[] =\n" + to_c_string(icon) + ";\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
